import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import io.github.safetimamovic.adjustability.Constants;
import io.github.safetimamovic.adjustability.config.CreatorConfig;
import io.github.safetimamovic.adjustability.config.PlayerConfig;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;
import net.minecraft.core.Holder;
import net.minecraft.core.registries.Registries;
import net.minecraft.gametest.framework.GameTestHelper;
import net.minecraft.world.item.enchantment.Enchantment;
import net.neoforged.neoforge.common.ModConfigSpec;
import net.neoforged.neoforge.common.ModConfigSpec.ValueSpec;

/**
 * Docs written from the code, so they can't drift: {@code docs/reference/config.md} (every setting of both config
 * files, from their specs) and {@code docs/reference/conflicts.md} (vanilla's conflicts, from the enchantment registry).
 * The {@code generated_docs} GameTest fails when a file on disk differs; {@code ./gradlew :fabric:runGametest
 * -PwriteDocs} writes them. Also checks the hand-written tables and the config screen's translations.
 */
final class ReferenceDocs
{
        private static final String HEADER = """
                <!-- Generated by the generated_docs GameTest. Don't edit by hand:
                     ./gradlew :fabric:runGametest -PwriteDocs -->
                """;

        private ReferenceDocs()
        {
        }

        /** Every generated page matches what's on disk (or is written, with {@code -PwriteDocs}). */
        static void generatedDocs(GameTestHelper helper)
        {
                Path root = repositoryRoot();
                boolean write = System.getenv("ADJUSTABILITY_WRITE_DOCS") != null;
                Map<String, String> pages = new LinkedHashMap<>();
                pages.put("docs/reference/config.md", configReference());
                pages.put("docs/reference/conflicts.md", conflictTable(helper));
                List<String> stale = new ArrayList<>();
                for (Map.Entry<String, String> page : pages.entrySet())
                {
                        Path file = root.resolve(page.getKey());
                        String onDisk = read(file);
                        if (page.getValue().equals(onDisk))
                        {
                                continue;
                        }
                        if (write)
                        {
                                write(file, page.getValue());
                                Constants.LOG.info("Wrote {}", file);
                        }
                        else
                        {
                                stale.add(page.getKey());
                        }
                }
                helper.assertTrue(stale.isEmpty(), "out of date (run ./gradlew :fabric:runGametest -PwriteDocs): " + stale);
                helper.succeed();
        }

        /**
         * The hand-written tables in {@code guide/server-config.md} list every setting with its real default, and
         * every setting and section has a name for the config screen.
         */
        static void handWrittenDocs(GameTestHelper helper)
        {
                String page = read(repositoryRoot().resolve("docs/guide/server-config.md"));
                JsonObject lang = lang();
                List<String> problems = new ArrayList<>();
                for (ModConfigSpec spec : List.of(CreatorConfig.SPEC, PlayerConfig.SPEC))
                {
                        walk(spec, spec.getSpec(), List.of(), (path, value) ->
                        {
                                String key = path.getLast();
                                String row = "| `" + key + "` | `" + format(value.getDefault()) + "` |";
                                if (!page.contains(row))
                                {
                                        problems.add("server-config.md has no row " + row);
                                }
                        }, section -> {});
                        walk(spec, spec.getSpec(), List.of(), (path, value) -> translated(lang, path, problems),
                                path -> translated(lang, path, problems));
                }
                if (!lang.has(Constants.MOD_ID + ".configuration.title"))
                {
                        problems.add("no translation " + Constants.MOD_ID + ".configuration.title");
                }
                helper.assertTrue(problems.isEmpty(), String.join("; ", problems));
                helper.succeed();
        }

        private static void translated(JsonObject lang, List<String> path, List<String> problems)
        {
                String key = Constants.MOD_ID + ".configuration." + path.getLast();
                if (!lang.has(key))
                {
                        problems.add("no translation " + key);
                }
        }

        static String configReference()
        {
                StringBuilder out = new StringBuilder(HEADER).append("""

                        # Config reference

                        Every setting with its default, as the mod defines them. The [server config](../guide/server-config.md)
                        and its examples explain them in more detail.
                        """);
                file(out, "adjustability-server.toml", """
                        Server settings (`config/adjustability-server.toml`, per world in single player). Synced to players, so their \
                        Adjust panel shows the server's rules.""", CreatorConfig.SPEC);
                file(out, "adjustability-client.toml", """
                        Player settings (`config/adjustability-client.toml`). Each player's own; also in game through the mod list \
                        or Mod Menu, and `/adjustability panel` for the panel.""", PlayerConfig.SPEC);
                return out.toString();
        }

        private static void file(StringBuilder out, String name, String about, ModConfigSpec spec)
        {
                out.append("\n## ").append(name).append("\n\n").append(about).append('\n');
                walk(spec, spec.getSpec(), List.of(), (path, value) -> out.append("| `").append(path.getLast())
                        .append("` | `").append(format(value.getDefault())).append("` | ")
                        .append(allowed(value)).append(" | ").append(description(value.getComment())).append(" |\n"),
                        path ->
                {
                        out.append("\n### [").append(String.join(".", path)).append("]\n\n");
                        String comment = spec.getLevelComment(path);
                        if (comment != null && !comment.isBlank())
                        {
                                out.append(cell(comment)).append("\n\n");
                        }
                        out.append("| Key | Default | Allowed | Description |\n|---|---|---|---|\n");
                });
        }

        /** Vanilla's conflict groups: every set of enchantments joined by {@code exclusive_set}, and who blocks whom. */
        static String conflictTable(GameTestHelper helper)
        {
                List<Holder.Reference<Enchantment>> all = helper.getLevel().registryAccess()
                        .lookupOrThrow(Registries.ENCHANTMENT).listElements()
                        .filter(holder -> holder.key().identifier().getNamespace().equals("minecraft"))
                        .sorted(Comparator.comparing(holder -> holder.key().identifier().getPath()))
                        .toList();
                Map<Holder<Enchantment>, Integer> group = new HashMap<>();
                List<List<Holder.Reference<Enchantment>>> groups = new ArrayList<>();
                for (Holder.Reference<Enchantment> start : all)
                {
                        if (group.containsKey(start))
                        {
                                continue;
                        }
                        List<Holder.Reference<Enchantment>> members = new ArrayList<>();
                        List<Holder.Reference<Enchantment>> queue = new ArrayList<>(List.of(start));
                        group.put(start, groups.size());
                        while (!queue.isEmpty())
                        {
                                Holder.Reference<Enchantment> next = queue.removeLast();
                                members.add(next);
                                for (Holder.Reference<Enchantment> other : all)
                                {
                                        if (!group.containsKey(other) && conflict(next, other))
                                        {
                                                group.put(other, groups.size());
                                                queue.add(other);
                                        }
                                }
                        }
                        members.sort(Comparator.comparing(holder -> holder.key().identifier().getPath()));
                        groups.add(members);
                }

                StringBuilder out = new StringBuilder(HEADER).append("""

                        # Vanilla conflicts

                        Every group of vanilla enchantments that conflict, read from Minecraft 26.3's `exclusive_set`s. An item \
                        can hold a whole group; one at a time is active (or more, where they don't conflict with each other, \
                        like Loyalty and Channeling). Datapacks and the server's [`[exclusivity]`](../guide/server-config.md#which-enchantments-conflict) \
                        settings can change these; [tags](../guide/tags.md) explains how.

                        """);
                for (List<Holder.Reference<Enchantment>> members : groups)
                {
                        if (members.size() < 2)
                        {
                                continue;
                        }
                        out.append("## ").append(members.stream().map(ReferenceDocs::name)
                                .collect(Collectors.joining(", "))).append("\n\n");
                        out.append("| Enchantment | Id | Max level | Conflicts with |\n|---|---|---|---|\n");
                        for (Holder.Reference<Enchantment> enchantment : members)
                        {
                                out.append("| ").append(name(enchantment)).append(" | `")
                                        .append(enchantment.key().identifier()).append("` | ")
                                        .append(enchantment.value().getMaxLevel()).append(" | ")
                                        .append(members.stream().filter(other -> conflict(enchantment, other))
                                                .map(ReferenceDocs::name).collect(Collectors.joining(", ")))
                                        .append(" |\n");
                        }
                        out.append('\n');
                }
                out.append("## No conflicts\n\n").append(groups.stream().filter(members -> members.size() == 1)
                        .map(members -> name(members.getFirst())).collect(Collectors.joining(", "))).append(".\n");
                return out.toString();
        }

        private static boolean conflict(Holder<Enchantment> a, Holder<Enchantment> b)
        {
                return !a.equals(b) && !Enchantment.areCompatible(a, b);
        }

        private static String name(Holder<Enchantment> enchantment)
        {
                return enchantment.value().description().getString();
        }

        private interface ValueVisitor
        {
                void visit(List<String> path, ValueSpec value);
        }

        private interface SectionVisitor
        {
                void visit(List<String> path);
        }

        /** Every value in file order, each section announced before its values. */
        private static void walk(ModConfigSpec spec, UnmodifiableConfig config, List<String> path, ValueVisitor values,
                SectionVisitor sections)
        {
                for (UnmodifiableConfig.Entry entry : config.entrySet())
                {
                        List<String> here = new ArrayList<>(path);
                        here.add(entry.getKey());
                        Object value = entry.getValue();
                        if (value instanceof UnmodifiableConfig section)
                        {
                                sections.visit(here);
                                walk(spec, section, here, values, sections);
                        }
                        else if (value instanceof ValueSpec valueSpec)
                        {
                                values.visit(here, valueSpec);
                        }
                }
        }

        static String format(Object value)
        {
                if (value instanceof List<?> list)
                {
                        return list.stream().map(element -> "\"" + element + "\"")
                                .collect(Collectors.joining(", ", "[", "]"));
                }
                return value instanceof Enum<?> constant ? constant.name() : String.valueOf(value);
        }

        /** The value's range or choices, which NeoForge appends to its comment. */
        private static String allowed(ValueSpec value)
        {
                if (value.getDefault() instanceof Boolean)
                {
                        return "`true`, `false`";
                }
                for (String line : lines(value.getComment()))
                {
                        if (line.startsWith("Range: "))
                        {
                                return "`" + line.substring("Range: ".length()).replace(" ~ ", "` – `") + "`";
                        }
                        if (line.startsWith("Allowed Values: "))
                        {
                                return List.of(line.substring("Allowed Values: ".length()).split(", ")).stream()
                                        .map(choice -> "`" + choice + "`").collect(Collectors.joining(", "));
                        }
                }
                return "";
        }

        /** The comment as written in the config, without the lines NeoForge appends. */
        private static String description(String comment)
        {
                return cell(lines(comment).stream().filter(line -> !line.startsWith("Default: ")
                        && !line.startsWith("Range: ") && !line.startsWith("Allowed Values: "))
                        .collect(Collectors.joining("\n")));
        }

        private static List<String> lines(String comment)
        {
                return comment == null ? List.of() : comment.replace("\r", "").lines().map(String::strip)
                        .filter(line -> !line.isEmpty()).toList();
        }

        private static String cell(String comment)
        {
                // Markdown table cell; VitePress would read <selectors> as an HTML tag.
                return comment == null ? "" : comment.strip().replace("\r", "").replace("\n", " ").replace("|", "\\|")
                        .replace("<", "&lt;").replace(">", "&gt;");
        }

        private static JsonObject lang()
        {
                String path = "/assets/" + Constants.MOD_ID + "/lang/en_us.json";
                try (InputStream in = ReferenceDocs.class.getResourceAsStream(path))
                {
                        if (in == null)
                        {
                                throw new IllegalStateException("missing " + path);
                        }
                        return JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
                }
                catch (IOException e)
                {
                        throw new IllegalStateException(e);
                }
        }

        /** The checkout the dev run was started from: the run directory is {@code <loader>/runs/<name>}. */
        private static Path repositoryRoot()
        {
                for (Path dir = Path.of("").toAbsolutePath(); dir != null; dir = dir.getParent())
                {
                        if (Files.exists(dir.resolve("settings.gradle")) && Files.isDirectory(dir.resolve("docs")))
                        {
                                return dir;
                        }
                }
                throw new IllegalStateException("not run from a checkout: " + Path.of("").toAbsolutePath());
        }

        private static String read(Path file)
        {
                try
                {
                        return Files.exists(file) ? Files.readString(file).replace("\r\n", "\n") : "";
                }
                catch (IOException e)
                {
                        throw new IllegalStateException(e);
                }
        }

        private static void write(Path file, String content)
        {
                try
                {
                        Files.createDirectories(file.getParent());
                        Files.writeString(file, content);
                }
                catch (IOException e)
                {
                        throw new IllegalStateException(e);
                }
        }
}
